def tr(lang: str, key: str, **kwargs) -> str:
    """Lookup localized string with English fallback."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    text = table.get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def localized_class_name(cid: int, default_short: str, lang: str) -> str:
    if lang == "de":
        return CLASS_SHORT_DE.get(cid, default_short)
    return default_short
